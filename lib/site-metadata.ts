/**
 * Locale-prefixed path, matching what `proxy.ts` actually serves: English is the
 * default locale and stays prefix-less, Turkish lives under `/tr`. This is the
 * same convention as `projectHref` in `lib/projects.ts` — if one changes, both do,
 * or the canonical URL stops matching the URL a visitor is on.
 */
export const localePath = (lang: Locale, path = "/"): string => {
  const suffix = path === "/" ? "" : path;
  return lang === "tr" ? `/tr${suffix}` : suffix || "/";
};

export const localeUrl = (lang: Locale, path = "/"): string =>
  `${SITE_ORIGIN}${localePath(lang, path)}`;

/**
 * The hreflang set for one page, in both locales plus `x-default`. Google uses
 * `x-default` for visitors whose language matches neither — English, here, since
 * it is the site's default locale.
 */
export const languageAlternates = (path = "/") => ({
  en: localeUrl("en", path),
  tr: localeUrl("tr", path),
  "x-default": localeUrl("en", path),
});

/**
 * The inverse of `localePath`: strips a `/tr` prefix back off, so a path can be
 * re-prefixed for the other locale. `/tr` and `/tr/` both come back as `/`,
 * which is the case the language switcher used to get wrong — it concatenated
 * `/tr` onto the home path `/` and produced `/tr/`, a URL that only exists to
 * 308 to `/tr`. Google logged that hop as "Page with redirect".
 */
export const stripLocalePrefix = (pathname: string): string =>
  pathname.replace(/^\/tr(?=\/|$)/, "").replace(/\/$/, "") || "/";

import type { Locale } from "@/app/[lang]/dictionaries";

/**
 * Canonical origin for every absolute URL the site emits — `metadataBase`,
 * canonicals, hreflang alternates, the sitemap and the JSON-LD graph.
 *
 * Overridable so a preview deployment describes itself instead of claiming to be
 * production: setting `NEXT_PUBLIC_SITE_URL` on a Vercel preview keeps its
 * canonicals pointing at the preview, which stops Google from indexing a branch
 * build under the real domain.
 */
export const SITE_ORIGIN = (
  process.env.NEXT_PUBLIC_SITE_URL ?? "https://burakhasici.com"
).replace(/\/+$/, "");

export const SITE_NAME = "Burak Haşıcı";

/**
 * The same name, typed the ways people actually type it: a search box on a
 * non-Turkish keyboard produces "Burak Hasici", and the site calls itself BH in
 * its own wordmark. Google reconciles diacritics well enough on its own, but
 * `alternateName` is the one place to say it outright — and this site is
 * competing against LinkedIn and Instagram profiles for the same name, where
 * every explicit signal counts.
 */
export const SITE_ALTERNATE_NAMES = ["Burak Hasici", "BH"];

/** Stable node ids, so the graph's nodes can reference each other rather than
 * repeating themselves — and so other pages can point at the same Person. */
export const PERSON_ID = `${SITE_ORIGIN}/#person`;
export const WEBSITE_ID = `${SITE_ORIGIN}/#website`;

